# ---------------------------------------------------------------- tiny DOM

VOID = {"meta", "link", "input", "br", "img", "hr", "source", "wbr", "area", "base", "col", "embed", "track"}


class Node:
    def __init__(self, tag, attrs, parent):
        self.tag, self.attrs, self.parent, self.children = tag, attrs, parent, []

    def classes(self):
        return set((self.attrs.get("class") or "").split())

    def walk(self):
        for c in self.children:
            if isinstance(c, Node):
                yield c
                yield from c.walk()

    def find_all(self, tag=None, cls=None):
        return [n for n in self.walk() if (tag is None or n.tag == tag) and (cls is None or cls in n.classes())]

    def find(self, tag=None, cls=None):
        found = self.find_all(tag, cls)
        return found[0] if found else None

    def inside(self, cls):
        n = self.parent
        while n is not None:
            if cls in n.classes():
                return True
            n = n.parent
        return False

    def text(self, drop=lambda n: False):
        out = []

        def collect(n):
            for c in n.children:
                if isinstance(c, str):
                    out.append(c)
                elif c.tag == "br":
                    out.append(" ")
                elif not drop(c):
                    collect(c)

        collect(self)
        return re.sub(r"\s+", " ", "".join(out)).strip()


class Builder(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = Node("root", {}, None)
        self.cur = self.root

    def handle_starttag(self, tag, attrs):
        node = Node(tag, dict(attrs), self.cur)
        self.cur.children.append(node)
        if tag not in VOID:
            self.cur = node

    def handle_startendtag(self, tag, attrs):
        self.cur.children.append(Node(tag, dict(attrs), self.cur))

    def handle_endtag(self, tag):
        n = self.cur
        while n is not None and n.tag != tag:
            n = n.parent
        if n is not None and n.parent is not None:
            self.cur = n.parent

    def handle_data(self, data):
        self.cur.children.append(data)


def parse(name):
    b = Builder()
    b.feed((ROOT / name).read_text(encoding="utf-8"))
    return b.root


# ---------------------------------------------------------------- reading the copy

def is_arrow_link(n):
    """A trailing 'Read more →' link is a call to action, not part of an answer."""
    return n.tag == "a" and n.text().endswith("→")


def page_text(doc):
    body = doc.find("body")
    return body.text() if body else ""


def guard(page, doc, phrases):
    text = page_text(doc).lower()
    for p in phrases:
        if p.lower() not in text:
            problems.append(f'{page}: the copy no longer says "{p}". Update tools/structured_data.py to match the page.')


def h1(doc):
    return doc.find("h1").text()


def lead(doc):
    return doc.find("p", "lead").text()


def brief(doc, label):
    """The paragraph of the page's AI brief that starts with this bold label."""
    for p in doc.find_all("p"):
        b = p.find("b")
        if p.inside("ai-brief") and b is not None and b.text() == label:
            rest = p.text()[len(label):].strip()
            return rest[:1].upper() + rest[1:]
    return None


def faq(doc):
    """Questions and answers as they stand on the page."""
    pairs = []
    for section in doc.find_all("section"):
        if section.attrs.get("id") == "questions":
            for item in section.find_all("div", "item"):
                q, a = item.find("h3"), item.find("p")
                if q and a:
                    pairs.append((q.text(), a.text(is_arrow_link)))
    for d in doc.find_all("details"):
        if d.inside("ai-brief"):
            continue
        q = d.find("summary")
        if q:
            pairs.append((q.text(), d.text(lambda n: n.tag == "summary" or is_arrow_link(n))))
    return pairs


