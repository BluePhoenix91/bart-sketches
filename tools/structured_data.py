# ---------------------------------------------------------------- writing

def block(graph):
    data = json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False, indent=1)
    data = data.replace("</", "<\\/")  # a closing tag inside the JSON would end the script element
    return f'{START}\n<script type="application/ld+json">\n{data}\n</script>\n{END}\n'


def inject(html, new_block):
    if START in html and END in html:
        return html[: html.index(START)] + new_block + html[html.index(END) + len(END) + 1:]
    if html.count("</head>") != 1:
        raise SystemExit("expected exactly one </head>")
    return html.replace("</head>", new_block + "</head>")


def main():
    check = "--check" in sys.argv[1:]
    docs = {name: parse(name) for name in PAGES}
    blocks = {name: block(build(docs)) for name, build in PAGES.items()}
    if problems:
        print("\n".join(problems))
        raise SystemExit("Nothing written.")
    changed = []
    for name, new_block in blocks.items():
        path = ROOT / name
        old = path.read_text(encoding="utf-8")
        new = inject(old, new_block)
        if new != old:
            changed.append(name)
            if not check:
                path.write_text(new, encoding="utf-8")
    if check and changed:
        raise SystemExit("Structured data is out of date in: " + ", ".join(changed))
    print("Up to date." if not changed else "Updated: " + ", ".join(changed))


if __name__ == "__main__":
    main()
