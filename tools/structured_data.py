def page_url(page):
    return SITE if page == "index.html" else SITE + page


def service_id(key):
    return f"{SITE}#delivery-{key}"


def business_ref():
    return {"@type": "ProfessionalService", "@id": BUSINESS, "name": "bart consulting", "url": SITE}


def service_ref(key):
    s = SERVICES[key]
    return {"@type": "Service", "@id": service_id(key), "name": s["name"], "url": page_url(s["page"])}


def service_description(key, docs):
    s = SERVICES[key]
    if s["description"]:
        return s["description"]
    text = brief(docs[s["page"]], "In short:")
    if not text:
        problems.append(f'{s["page"]}: no "In short:" line in the AI brief to describe the {s["name"]}.')
    return text


def offer(key):
    s = SERVICES[key]
    o = {"@type": "Offer", "priceCurrency": "EUR"}
    if "min_price" in s:
        o["priceSpecification"] = {
            "@type": "PriceSpecification", "minPrice": s["min_price"], "priceCurrency": "EUR", "valueAddedTaxIncluded": False,
        }
